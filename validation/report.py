#!/usr/bin/env python3
"""Turn the CSV outputs of run_demo.sh into results/validation_report.md."""
import csv
import os
import sys

RESULTS = sys.argv[1] if len(sys.argv) > 1 else "results"


def read(name):
    path = os.path.join(RESULTS, name)
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def table(rows, cols, headers=None):
    if not rows:
        return "_(no rows)_\n"
    headers = headers or cols
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r[c]).replace("|", "\\|") for c in cols) + " |")
    return "\n".join(out) + "\n"


def money(v):
    return f"{float(v):,.2f}"


checks = read("validation_results.csv")
tests = read("procedure_tests.csv")
negative = read("negative_test.csv")
sites = read("site_totals.csv")
env = open(os.path.join(RESULTS, "environment.txt"), encoding="utf-8").read().strip() \
    if os.path.exists(os.path.join(RESULTS, "environment.txt")) else ""

n_pass = sum(r["status"] == "PASS" for r in checks)
t_pass = sum(r["status"] == "PASS" for r in tests)
sites_ok = sum(r["all_match"] == "t" for r in sites)

md = ["# Validation report", "",
      "Generated by `run_demo.sh` - do not edit by hand.", "",
      "```", env, "```", "",
      f"**Reconciliation checks:** {n_pass}/{len(checks)} PASS  ",
      f"**Procedure behaviour tests:** {t_pass}/{len(tests)} PASS  ",
      f"**Sites with all five amounts identical:** {sites_ok}/{len(sites)}  ",
      f"**Negative test (3 injected defects):** {len(negative)} checks turned FAIL, as expected", "",
      "## 1. Reconciliation checks (source `ora_src` vs target `erp`)", "",
      table(checks, ["check_no", "category", "check_name", "source_value", "target_value", "detail", "status"],
            ["#", "Category", "Check", "Source", "Target", "Detail", "Result"]),
      "## 2. Procedure behaviour tests (run in a rolled-back transaction)", "",
      table(tests, ["test_no", "test_name", "expected", "actual", "status"],
            ["#", "Test", "Expected", "Actual", "Result"]),
      "## 3. Negative test - checks that FAIL after injecting 3 defects", "",
      table(negative, ["check_no", "category", "check_name", "source_value", "target_value", "status"],
            ["#", "Category", "Check", "Source", "Target", "Result"]),
      "## 4. Per-site totals (source = target for every site)", "",
      table([{**r,
              "contract": money(r["tgt_contract_amt"]), "po": money(r["tgt_po_amt"]),
              "budget": money(r["tgt_budget_amt"]),
              "match": "PASS" if r["all_match"] == "t" else "FAIL"} for r in sites],
            ["site_id", "contract", "po", "budget", "match"],
            ["Site", "Contract amount", "PO amount", "Budget amount", "Src = Tgt (5 metrics)"]),
      ]
with open(os.path.join(RESULTS, "validation_report.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(md))
print(f"checks {n_pass}/{len(checks)} PASS, tests {t_pass}/{len(tests)} PASS, "
      f"sites {sites_ok}/{len(sites)} match, negative-test FAIL rows {len(negative)}")
