--------------------------------------------------------------------------------
-- TARGET: PostgreSQL 14+ schema "erp" converted from oracle/01_schema.sql
--
-- Main decisions (full table in README / docs/conversion-notes.md):
--   NUMBER(10|12) keys      -> bigint  (NUMBER(10) can exceed int4's 2,147,483,647)
--   NUMBER(5) / NUMBER(4)   -> integer / smallint
--   NUMBER(p,s) money       -> numeric(p,s)  (never float/double for money)
--   VARCHAR2(n [CHAR|BYTE]) -> varchar(n)    (PostgreSQL always counts characters)
--   VARCHAR2(4000) remarks  -> text
--   CHAR(1) 'Y'/'N' flags   -> boolean       (renamed *_yn -> is_*)
--   CHAR(1)/VARCHAR2 codes  -> varchar(n) + CHECK  (avoid blank-padded char(n))
--   DATE (business dates)   -> date          (pre-check proves no time part exists)
--   DATE (audit columns)    -> timestamp(0)  (Oracle DATE keeps time to the second)
--   SEQUENCE + BI trigger   -> GENERATED BY DEFAULT AS IDENTITY
--------------------------------------------------------------------------------
DROP SCHEMA IF EXISTS erp CASCADE;
CREATE SCHEMA erp;

CREATE TABLE erp.site (
    site_id        bigint        GENERATED BY DEFAULT AS IDENTITY,
    site_code      varchar(20)   NOT NULL,
    site_name      varchar(200)  NOT NULL,
    region         varchar(50)   NOT NULL,
    client_name    varchar(200),
    start_date     date          NOT NULL,
    end_date       date,
    status         varchar(1)    NOT NULL DEFAULT 'P',
    manager_name   varchar(100),
    created_at     timestamp(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT pk_site        PRIMARY KEY (site_id),
    CONSTRAINT uk_site_code   UNIQUE (site_code),
    CONSTRAINT ck_site_status CHECK (status IN ('P','A','C'))
);

CREATE TABLE erp.contract_hdr (
    contract_id    bigint        GENERATED BY DEFAULT AS IDENTITY,
    contract_no    varchar(30)   NOT NULL,
    site_id        bigint        NOT NULL,
    vendor_name    varchar(200)  NOT NULL,
    contract_type  varchar(3)    NOT NULL,
    contract_date  date          NOT NULL,
    start_date     date,
    end_date       date,
    currency       char(3)       NOT NULL DEFAULT 'KRW',
    total_amount   numeric(18,2) NOT NULL DEFAULT 0,
    vat_amount     numeric(18,2) NOT NULL DEFAULT 0,
    status         varchar(10)   NOT NULL DEFAULT 'DRAFT',
    retention_rate numeric(5,2),
    remarks        text,
    created_at     timestamp(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    updated_at     timestamp(0),
    CONSTRAINT pk_contract_hdr    PRIMARY KEY (contract_id),
    CONSTRAINT uk_contract_no     UNIQUE (contract_no),
    CONSTRAINT fk_contract_site   FOREIGN KEY (site_id) REFERENCES erp.site (site_id),
    CONSTRAINT ck_contract_type   CHECK (contract_type IN ('SUB','MAT','EQP','SVC')),
    CONSTRAINT ck_contract_status CHECK (status IN ('DRAFT','APPROVED','CLOSED','CANCELLED')),
    CONSTRAINT ck_contract_remarks_len CHECK (char_length(remarks) <= 4000)
);
CREATE INDEX ix_contract_hdr_site ON erp.contract_hdr (site_id);

CREATE TABLE erp.contract_dtl (
    contract_id    bigint        NOT NULL,
    line_no        integer       NOT NULL,
    item_code      varchar(30)   NOT NULL,
    item_name      varchar(200)  NOT NULL,
    spec           varchar(200),
    unit           varchar(10)   NOT NULL,
    quantity       numeric(15,3) NOT NULL,
    unit_price     numeric(15,2) NOT NULL,
    amount         numeric(18,2) NOT NULL,
    cost_code      varchar(20)   NOT NULL,
    CONSTRAINT pk_contract_dtl     PRIMARY KEY (contract_id, line_no),
    CONSTRAINT fk_contract_dtl_hdr FOREIGN KEY (contract_id) REFERENCES erp.contract_hdr (contract_id)
);

CREATE TABLE erp.purchase_order (
    po_id          bigint        GENERATED BY DEFAULT AS IDENTITY,
    po_no          varchar(30)   NOT NULL,
    site_id        bigint        NOT NULL,
    contract_id    bigint,
    vendor_name    varchar(200)  NOT NULL,
    po_date        date          NOT NULL,
    delivery_date  date,
    cost_code      varchar(20)   NOT NULL,
    po_amount      numeric(18,2) NOT NULL,
    status         varchar(10)   NOT NULL DEFAULT 'ISSUED',
    is_urgent      boolean       NOT NULL DEFAULT false,
    remarks        varchar(1000),
    created_at     timestamp(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT pk_purchase_order PRIMARY KEY (po_id),
    CONSTRAINT uk_po_no          UNIQUE (po_no),
    CONSTRAINT fk_po_site        FOREIGN KEY (site_id)     REFERENCES erp.site (site_id),
    CONSTRAINT fk_po_contract    FOREIGN KEY (contract_id) REFERENCES erp.contract_hdr (contract_id),
    CONSTRAINT ck_po_status      CHECK (status IN ('ISSUED','RECEIVED','CANCELLED'))
);
CREATE INDEX ix_po_site     ON erp.purchase_order (site_id);
CREATE INDEX ix_po_contract ON erp.purchase_order (contract_id);   -- Oracle does not auto-index FKs either

CREATE TABLE erp.budget (
    budget_id      bigint        GENERATED BY DEFAULT AS IDENTITY,
    site_id        bigint        NOT NULL,
    fiscal_year    smallint      NOT NULL,
    cost_code      varchar(20)   NOT NULL,
    budget_amount  numeric(18,2) NOT NULL,
    revised_amount numeric(18,2),
    is_approved    boolean       NOT NULL DEFAULT false,
    created_at     timestamp(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT pk_budget      PRIMARY KEY (budget_id),
    CONSTRAINT uk_budget      UNIQUE (site_id, fiscal_year, cost_code),
    CONSTRAINT fk_budget_site FOREIGN KEY (site_id) REFERENCES erp.site (site_id)
);
